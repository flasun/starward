import type { BodyDef } from "@/components/starfield/system";

type Seed = {
  id: string;
  name: string;
  x: number;
  y?: number;
  z: number;
  color: [number, number, number];
  span: number;
  form: NonNullable<BodyDef["form"]>;
  group: string;
  place: string;
  year: string;
  moons: string;
  blurb: string;
  goal?: boolean;
  hollow?: boolean;
};

function place(chapter: string, seed: Seed): BodyDef {
  return {
    id: seed.id,
    name: seed.name,
    au: 0,
    diameterKm: 1,
    color: seed.color,
    angle: 0,
    periodDays: 0,
    moons: seed.moons,
    year: seed.year,
    blurb: seed.blurb,
    goal: seed.goal !== false,
    nav: true,
    group: seed.group,
    place: seed.place,
    at: { x: seed.x, y: seed.y ?? 0, z: seed.z },
    span: seed.span,
    form: seed.form,
    chapter,
    ...(seed.hollow ? { hollow: true } : {}),
  };
}

const star = (seed: Seed) => place("stars", seed);
const galaxy = (seed: Seed) => place("galaxy", seed);
const local = (seed: Seed) => place("local", seed);
const web = (seed: Seed) => place("web", seed);
const deep = (seed: Seed) => place("deep", seed);

